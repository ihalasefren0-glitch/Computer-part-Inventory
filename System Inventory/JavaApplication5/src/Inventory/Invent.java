    private void adjustStock(boolean add) {
        int id = selectedId(jTable2);
        if (id < 0) {
            JOptionPane.showMessageDialog(this, "Select a product first.");
            return;
        }
        String amountText = JOptionPane.showInputDialog(
                this,
                add ? "How many pieces to add?" : "How many pieces to take out?",
                add ? "Add Stock" : "Stock Out",
                JOptionPane.PLAIN_MESSAGE
        );
        if (amountText == null) {
            return;
        }
        int amount;
        try {
            amount = Integer.parseInt(amountText.trim());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Enter a whole number.");
            return;
        }
        if (amount <= 0) {
            JOptionPane.showMessageDialog(this, "Enter a number greater than 0.");
            return;
        }

        String sql = add
                ? "UPDATE products SET stock = stock + ?, status = CASE "
                + "WHEN stock + ? <= 0 THEN 'Out of Stock' "
                + "WHEN stock + ? < 5 THEN 'Low Stock' "
                + "ELSE 'In Stock' END WHERE id = ?"
                : "UPDATE products SET stock = stock - ?, status = CASE "
                + "WHEN stock - ? <= 0 THEN 'Out of Stock' "
                + "WHEN stock - ? < 5 THEN 'Low Stock' "
                + "ELSE 'In Stock' END WHERE id = ? AND stock >= ?";
        try (Connection con = DB_Connection.getConnection();
                PreparedStatement pst = con.prepareStatement(sql)) {
            pst.setInt(1, amount);
            pst.setInt(2, amount);
            pst.setInt(3, amount);
            pst.setInt(4, id);
            if (!add) {
                pst.setInt(5, amount);
            }
            int updated = pst.executeUpdate();
            if (updated == 0) {
                JOptionPane.showMessageDialog(this, "Not enough stock to take out.");
                return;
            }
            if (add) {
                recordStockEntry(id, amount);
            }
            JOptionPane.showMessageDialog(this, add ? "Stock added." : "Stock updated.");
            reloadProducts();
        } catch (SQLException e) {
            showDbError(e);
        }
    }

