    private void fillTable(DefaultTableModel model, String keyword, String filter, boolean full) {
        model.setRowCount(0);
        StringBuilder sql = new StringBuilder(
                "SELECT id, product_name, brand, model, category, price, stock, status FROM products WHERE 1=1");
        if (!keyword.isEmpty()) {
            sql.append(" AND (product_name LIKE ? OR brand LIKE ? OR model LIKE ? OR category LIKE ? OR status LIKE ?)");
        }
        if ("low".equals(filter)) {
            sql.append(" AND stock > 0 AND stock < 5");
        } else if ("out".equals(filter)) {
            sql.append(" AND stock <= 0");
        }
        sql.append(" ORDER BY id ASC");

        try (Connection con = DB_Connection.getConnection();
                PreparedStatement pst = con.prepareStatement(sql.toString())) {
            if (!keyword.isEmpty()) {
                String like = "%" + keyword + "%";
                for (int i = 1; i <= 5; i++) {
                    pst.setString(i, like);
                }
            }
            try (ResultSet rs = pst.executeQuery()) {
                while (rs.next()) {
                    if (full) {
                        model.addRow(new Object[]{
                            rs.getInt("id"),
                            rs.getString("product_name"),
                            rs.getString("brand"),
                            rs.getString("model"),
                            rs.getString("category"),
                            String.format(java.util.Locale.US, "%.2f", rs.getDouble("price")),
                            rs.getInt("stock"),
                            rs.getString("status")
                        });
                    } else {
                        model.addRow(new Object[]{
                            rs.getInt("id"),
                            rs.getString("product_name"),
                            rs.getString("brand"),
                            rs.getInt("stock"),
                            rs.getString("status")
                        });
                    }
                }
            }
            dbErrorShown = false;
        } catch (SQLException e) {
            showDbError(e);
        }
    }

    private void loadReport() {
        String summary = "SELECT COUNT(*) AS total, COALESCE(SUM(stock), 0) AS units FROM products";
        try (Connection con = DB_Connection.getConnection()) {
            try (PreparedStatement summaryStmt = con.prepareStatement(summary);
                    ResultSet totals = summaryStmt.executeQuery()) {
                if (totals.next()) {
                    statProducts.setText(String.valueOf(totals.getInt("total")));
                    statUnits.setText(String.valueOf(totals.getInt("units")));
                }
            }
            fillDashboardLists(con);
            loadReportRows(con);
            dbErrorShown = false;
        } catch (SQLException e) {
            reportRows.clear();
            showReportPage();
            showDbError(e);
        }
    }

    private void loadReportRows(Connection con) throws SQLException {
        reportRows.clear();
        reportPage = 0;
        String sql = "SELECT e.TransactionID, DATE_FORMAT(e.EntryDate, '%Y-%m-%d') AS entry_date, "
                + "p.product_name, p.model, p.brand, e.Amount "
                + "FROM stock_entries e JOIN products p ON p.id = e.ProductID ORDER BY e.EntryID";
        try (PreparedStatement pst = con.prepareStatement(sql);
                ResultSet rs = pst.executeQuery()) {
            while (rs.next()) {
                reportRows.add(new Object[]{
                    rs.getString("TransactionID"),
                    rs.getString("entry_date"),
                    rs.getString("product_name"),
                    rs.getString("model"),
                    rs.getString("brand"),
                    rs.getInt("Amount")
                });
            }
        }
        showReportPage();
    }

    private void showReportPage() {
        if (reportModel == null) {
            return;
        }
        int total = reportRows.size();
        int pages = Math.max(1, (int) Math.ceil(total / (double) REPORT_PAGE_SIZE));
        if (reportPage >= pages) {
            reportPage = pages - 1;
        }
        if (reportPage < 0) {
            reportPage = 0;
        }
        int start = reportPage * REPORT_PAGE_SIZE;
        int end = Math.min(start + REPORT_PAGE_SIZE, total);
        reportModel.setRowCount(0);
        for (int i = start; i < end; i++) {
            Object[] row = reportRows.get(i);
            reportModel.addRow(new Object[]{
                i + 1, row[0], row[1], row[2], row[3], row[4], row[5]
            });
        }
        int from = total == 0 ? 0 : start + 1;
        reportInfo.setText("Showing " + from + " to " + end + " of " + total + " entries");
        reportPrev.setEnabled(reportPage > 0);
        reportNext.setEnabled(end < total);
    }

    public void recordStockEntry(int productId, int amount) {
        if (productId <= 0 || amount <= 0) {
            return;
        }
        String sql = "INSERT INTO stock_entries (TransactionID, EntryDate, ProductID, Amount) "
                + "SELECT CONCAT('TRM-', DATE_FORMAT(CURDATE(), '%m%y'), LPAD(n + 1, 3, '0')), CURDATE(), ?, ? "
                + "FROM (SELECT COALESCE(MAX(EntryID), 0) AS n FROM stock_entries) seq";
        try (Connection con = DB_Connection.getConnection();
                PreparedStatement pst = con.prepareStatement(sql)) {
            pst.setInt(1, productId);
            pst.setInt(2, amount);
            pst.executeUpdate();
        } catch (SQLException e) {
            showDbError(e);
        }
    }

    private void fillDashboardLists(Connection con) throws SQLException {
        StringBuilder outLines = new StringBuilder();
        try (PreparedStatement pst = con.prepareStatement(
                "SELECT product_name, category FROM products WHERE stock <= 0 ORDER BY product_name");
                ResultSet rs = pst.executeQuery()) {
            while (rs.next()) {
                outLines.append(rs.getString("product_name"))
                        .append(" (")
                        .append(rs.getString("category"))
                        .append(")\n");
            }
        }
        outStockText.setText(outLines.length() == 0 ? "None" : outLines.toString().trim());

        StringBuilder lowLines = new StringBuilder();
        try (PreparedStatement pst = con.prepareStatement(
                "SELECT product_name, category, stock FROM products WHERE stock > 0 AND stock < 5 ORDER BY stock, product_name");
                ResultSet rs = pst.executeQuery()) {
            while (rs.next()) {
                lowLines.append(rs.getString("product_name"))
                        .append(" - ")
                        .append(rs.getInt("stock"))
                        .append(" left (")
                        .append(rs.getString("category"))
                        .append(")\n");
            }
        }
        lowStockText.setText(lowLines.length() == 0 ? "None" : lowLines.toString().trim());
        outStockText.setCaretPosition(0);
        lowStockText.setCaretPosition(0);
    }

