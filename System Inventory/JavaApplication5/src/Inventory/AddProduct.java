    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String productName = Pname.getText().trim();
        String brand = Bname.getText().trim();
        String model = Mname.getText().trim();
        String category = Cname.getText().trim();
        String priceText = priceField.getText().trim();
        String stockText = Sname.getText().trim();
        String status = String.valueOf(statusBox.getSelectedItem());

        if (productName.isEmpty() || brand.isEmpty() || model.isEmpty()
                || category.isEmpty() || priceText.isEmpty() || stockText.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill in all fields!");
            return;
        }

        double price;
        int stockNumber;
        try {
            price = Double.parseDouble(priceText);
            stockNumber = Integer.parseInt(stockText);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Price and stock must be numbers!");
            return;
        }
        if (price < 0 || stockNumber < 0) {
            JOptionPane.showMessageDialog(this, "Price and stock cannot be negative!");
            return;
        }

        String sql;
        if (stockOnly) {
            sql = "UPDATE products SET stock=?, status=? WHERE id=?";
        } else if (editingId > 0) {
            sql = "UPDATE products SET product_name=?, brand=?, model=?, category=?, price=?, stock=?, status=? WHERE id=?";
        } else {
            sql = "INSERT INTO products (product_name, brand, model, category, price, stock, status) VALUES (?, ?, ?, ?, ?, ?, ?)";
        }

        try (Connection con = DB_Connection.getConnection();
                PreparedStatement pst = con.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            if (stockOnly) {
                pst.setInt(1, stockNumber);
                pst.setString(2, status);
                pst.setInt(3, editingId);
            } else {
                pst.setString(1, productName);
                pst.setString(2, brand);
                pst.setString(3, model);
                pst.setString(4, category);
                pst.setDouble(5, price);
                pst.setInt(6, stockNumber);
                pst.setString(7, status);
                if (editingId > 0) {
                    pst.setInt(8, editingId);
                }
            }
            pst.executeUpdate();
            if (!stockOnly && editingId <= 0 && stockNumber > 0 && parentFrame != null) {
                try (ResultSet keys = pst.getGeneratedKeys()) {
                    if (keys.next()) {
                        parentFrame.recordStockEntry(keys.getInt(1), stockNumber);
                    }
                }
            }
            JOptionPane.showMessageDialog(this,
                    stockOnly ? "Stock Updated Successfully!"
                    : editingId > 0 ? "Product Updated Successfully!" : "Product Added Successfully!");
            if (parentFrame != null) {
                parentFrame.reloadProducts();
            }
            if (editingId > 0) {
                dispose();
            } else {
                clearFields();
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_jButton1ActionPerformed


    private void loadExisting() {
        String sql = "SELECT product_name, brand, model, category, price, stock, status FROM products WHERE id = ?";
        try (Connection con = DB_Connection.getConnection();
                PreparedStatement pst = con.prepareStatement(sql)) {
            pst.setInt(1, editingId);
            try (ResultSet rs = pst.executeQuery()) {
                if (!rs.next()) {
                    JOptionPane.showMessageDialog(this, "That product is no longer in the inventory.");
                    dispose();
                    return;
                }
                Pname.setText(rs.getString("product_name"));
                Bname.setText(rs.getString("brand"));
                Mname.setText(rs.getString("model"));
                Cname.setText(rs.getString("category"));
                priceField.setText(String.format(java.util.Locale.US, "%.2f", rs.getDouble("price")));
                Sname.setText(String.valueOf(rs.getInt("stock")));
                statusBox.setSelectedItem(rs.getString("status"));
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
            dispose();
        }
    }

    private void clearFields() {
        Pname.setText("");
        Bname.setText("");
        Mname.setText("");
        Cname.setText("");
        priceField.setText("");
        Sname.setText("");
        statusBox.setSelectedIndex(0);
        Pname.requestFocus();
    }

