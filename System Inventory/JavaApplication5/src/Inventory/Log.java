    private String login(String username, String password) {
        if (username.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter your username and password.");
            return null;
        }
        try (Connection con = DB_Connection.getConnection()) {
            String adminRole = accountRole(con, "admin", "Admin", username, password);
            if (adminRole != null) {
                return adminRole.isEmpty() ? null : adminRole;
            }
            String employeeRole = accountRole(con, "employee", "Employee", username, password);
            if (employeeRole != null) {
                return employeeRole.isEmpty() ? null : employeeRole;
            }
            JOptionPane.showMessageDialog(this, "Invalid username or password!");
            return null;
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Cannot reach the user table.\n" + e.getMessage());
            return null;
        }
    }

    private String accountRole(Connection con, String table, String role, String username, String password) throws SQLException {
        String sql = "SELECT AccountStatus FROM " + table + " WHERE Username = ? AND Password = ?";
        try (PreparedStatement pst = con.prepareStatement(sql)) {
            pst.setString(1, username);
            pst.setString(2, password);
            try (ResultSet rs = pst.executeQuery()) {
                if (!rs.next()) {
                    return null;
                }
                String status = rs.getString("AccountStatus");
                if (status == null || !status.equalsIgnoreCase("Active")) {
                    JOptionPane.showMessageDialog(this, "This account is inactive.");
                    return "";
                }
                return role;
            }
        }
    }

